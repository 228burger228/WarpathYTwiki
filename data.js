function fmt(n) {
  if (n >= 1000000) return (n/1000000).toFixed(1) + 'M';
  if (n >= 1000)    return (n/1000).toFixed(1) + 'K';
  return n.toString();
}

function calcUnit(typeId, level, offId, eqId) {
  const u = UNIT_TYPES.find(x => x.id === typeId) || UNIT_TYPES[0];
  const m = LEVEL_MULT[level] || 1;
  const o = OFFICERS.find(x => x.id === offId)  || OFFICERS[0];
  const e = EQUIPMENT.find(x => x.id === eqId)  || EQUIPMENT[0];
  const am = 1 + (o.atkB + e.atkB) / 100;
  const dm = 1 + (o.defB + e.defB) / 100;
  const hm = 1 + (o.hpB  + e.hpB)  / 100;
  return {
    atk:   Math.round(u.baseAtk  * m * am),
    def:   Math.round(u.baseDef  * m * dm),
    hp:    Math.round(u.baseHP   * m * hm),
    mov:   u.baseMov,
    cost:  Math.round(u.baseCost * m),
    power: Math.round((u.baseAtk + u.baseDef + u.baseHP * 0.05) * m * ((am+dm+hm)/3)),
  };
}

function buildTicker() {
  const el = document.getElementById('ticker-track');
  if (!el) return;
  [...TICKER, ...TICKER].forEach(t => {
    const s = document.createElement('span');
    s.className = 'ticker-item';
    s.textContent = t;
    el.appendChild(s);
  });
}

function setActiveNav() {
  const page = location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav-links a').forEach(a => {
    const h = a.getAttribute('href').split('/').pop();
    a.classList.toggle('active', h === page);
  });
}

function buildYtStrip(id) {
  const el = document.getElementById(id);
  if (!el) return;
  [...YOUTUBERS, ...YOUTUBERS].forEach(y => {
    const a = document.createElement('a');
    a.className = 'yt-card'; a.href = y.yt; a.target = '_blank';
    a.innerHTML = `<div class="yt-avatar">${y.emoji}</div><div><div class="yt-name">${y.name}${y.approved ? '' : ' ✦'}</div><div class="yt-subs">${y.subs} подписчиков</div></div>`;
    el.appendChild(a);
  });
}

function openModal(id)  { document.getElementById(id)?.classList.add('open'); }
function closeModal(id) { document.getElementById(id)?.classList.remove('open'); }

function initModals() {
  document.querySelectorAll('.modal-bg').forEach(m => {
    m.addEventListener('click', e => { if (e.target === m) m.classList.remove('open'); });
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'Escape') document.querySelectorAll('.modal-bg.open').forEach(m => m.classList.remove('open'));
  });
}

function initFadeUp() {
  const obs = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('visible'); });
  }, { threshold: 0.07 });
  document.querySelectorAll('.fade-up').forEach(el => obs.observe(el));
}

function initShared() {
  buildTicker();
  setActiveNav();
  initFadeUp();
  initModals();
  if (typeof applyLang === 'function') applyLang();
}

/* ── ЭКСПОРТ БАЗЫ ЗНАНИЙ ДЛЯ WORKER ─────────
   Эта функция генерирует системный промпт
   для Claude на основе всех данных выше.
   Используется в ai-chat.html.               */
function buildAIContext() {
  const units = UNIT_TYPES.map(u => {
    const full = UNIT_TYPES_FULL.find(x => x.id === u.id);
    if (!full) return `${u.label}: базовый юнит`;
    return `${full.emoji} ${full.label} (${full.tier}-тир): роль=${full.role}, сильные стороны=${full.strengths?.join(', ')}, слабости=${full.weaknesses?.join(', ')}, контрит=${full.counters?.join(', ')}, контрится=${full.counteredBy?.join(', ')}`;
  }).join('\n');

  const officers = OFFICERS_FULL.map(o =>
    `${o.emoji} ${o.name} (${o.tier}-тир, ${o.generation}пок): специализация=${o.specialization}, лучший с=${o.bestWith?.join(', ')}, совет=${o.tip}`
  ).join('\n');

  const meta = META_RULES.map(r => `• ${r.rule}: ${r.explanation}`).join('\n');

  return `ЮНИТЫ:\n${units}\n\nОФИЦЕРЫ:\n${officers}\n\nМЕТА-ПРАВИЛА:\n${meta}`;
}
